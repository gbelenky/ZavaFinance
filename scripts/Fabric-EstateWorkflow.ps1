#Requires -Version 7.0
Set-StrictMode -Version Latest

function Export-FabricEstate {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$SourceConfig,
        [Parameter(Mandatory)][string]$OutputPath,
        [switch]$InventoryOnly,
        [switch]$SourceQuiesced,
        [switch]$DefinitionContentApproved,
        [switch]$AllowPreviewDataAgent,
        [string]$SqlClientDirectory
    )
    $config = Read-EstateSource $SourceConfig
    Assert-EstateLocalPath $OutputPath -OutsideRepository
    if (!$InventoryOnly -and (!$SourceQuiesced -or !$DefinitionContentApproved)) {
        throw 'Full export requires -SourceQuiesced and -DefinitionContentApproved. Use -InventoryOnly first.'
    }
    if (Test-Path -LiteralPath $OutputPath) { throw 'Choose a new export directory. Partial or completed exports are never overwritten.' }
    Assert-EstateTenant $config.tenantId
    Assert-EstateFabricAuth $config.tenantId
    [void](New-Item -ItemType Directory -Path $OutputPath)
    $payload = Join-Path $OutputPath 'payload'
    [void](New-Item -ItemType Directory -Path $payload)
    $manifest = [ordered]@{
        version = 1; status = 'incomplete'; sourceTenantId = $config.tenantId
        startedUtc = [DateTimeOffset]::UtcNow.ToString('o'); finishedUtc = $null
        consistency = 'Operator-quiesced estate; before/after metadata, OneLake listing and SQL reconciliation.'
        history = 'Physical Delta directories including retained transaction logs and data files; vacuumed history cannot be recovered.'
        workspaces = @(); items = @(); blockers = @(); files = @()
    }
    $manifestPath = Join-Path $OutputPath 'manifest.json'
    Write-EstateJson $manifestPath $manifest
    try {
        foreach ($workspace in $config.workspaces) {
            $snapshot = Get-EstateWorkspaceInventory $workspace.id
            $manifest.workspaces += ,$snapshot
            if (@($snapshot.folders).Count) {
                $manifest.blockers += "Workspace $($workspace.id) contains folders; reviewed folder recreation/mapping is required before a whole-workspace export."
            }
            foreach ($source in $snapshot.items) {
                # The SQL analytics endpoint is generated by its Lakehouse, not an independently restored item.
                if ($source.type -eq 'SQLEndpoint') {
                    if ($source.id -notin @($snapshot.lakehouseSqlEndpointIds)) {
                        $manifest.blockers += "Unowned SQL analytics endpoint: $($source.id)"
                    }
                    continue
                }
                if ($source.type -notin 'Lakehouse','Notebook','DataAgent') {
                    $manifest.blockers += "Unsupported item $($source.id) ($($source.type)): add a reviewed type-specific data/definition migration before exporting the whole estate."
                    continue
                }
                if ($source.type -eq 'DataAgent' -and !$AllowPreviewDataAgent) {
                    $manifest.blockers += "DataAgent $($source.id) requires explicit -AllowPreviewDataAgent for its Preview definition/ALM route."
                }
                $item = [ordered]@{
                    id = $source.id; workspaceId = $workspace.id; displayName = $source.displayName
                    type = $source.type; definitionPath = "items/$($source.id)/definition"
                    dependencies = @(); lakehouse = $null
                    description = $(if ($source.Contains('description')) {$source.description} else {''})
                }
                if ($source.type -eq 'Lakehouse') {
                    $settings = @($workspace.lakehouses | Where-Object { $_.id -eq $source.id })
                    if ($settings.Count -ne 1) {
                        $manifest.blockers += "Lakehouse $($source.id) needs one SQL endpoint entry in the source configuration."
                    } else {
                        $item.lakehouse = $settings[0]
                        $item.lakehouse['areas'] = @{}
                        $item.lakehouse['sqlSnapshot'] = $null
                        $item.lakehouse['properties'] = $source.properties
                        Assert-EstateLakehouseEndpoint $source $settings[0]
                    }
                    if (@($snapshot.shortcuts[$source.id]).Count) {
                        $manifest.blockers += "Lakehouse $($source.id) contains shortcuts. Materialize their data or implement approved target rebinding; copying a shortcut is not an independent backup."
                    }
                }
                if ($source.type -in 'Notebook','Lakehouse' -and @($snapshot.schedules[$source.id]).Count) {
                    $manifest.blockers += "$($source.type) $($source.id) has schedules. Migrate schedule ownership/time zones explicitly; automatic re-enablement is not supported."
                }
                $manifest.items += ,$item
            }
            foreach ($configured in $workspace.lakehouses) {
                if ($configured.id -notin @($snapshot.items | Where-Object { $_.type -eq 'Lakehouse' } | ForEach-Object { $_.id })) {
                    $manifest.blockers += "Configured Lakehouse $($configured.id) is absent from workspace $($workspace.id)."
                }
            }
        }
        Write-EstateJson (Join-Path $payload 'inventory.json') $manifest.workspaces
        if ($InventoryOnly -or $manifest.blockers.Count) {
            $manifest.status = if ($manifest.blockers.Count) { 'blocked' } else { 'inventoryOnly' }
            Write-EstateJson $manifestPath $manifest
            if ($manifest.blockers.Count) { throw "Inventory has $($manifest.blockers.Count) blockers. Review manifest.json; no financial data was exported." }
            return [ordered]@{ status='inventoryOnly'; manifest=$manifestPath; itemCount=$manifest.items.Count; usableForImport=$false }
        }

        # Capture every source before copying any data, then recheck the whole estate at the end.
        foreach ($item in $manifest.items) {
            $definition = Resolve-EstatePath $payload $item.definitionPath
            Export-EstateDefinition $item.workspaceId $item.id $item.type $definition
            $text = Get-EstateDefinitionText $definition
            Assert-EstateDefinitionSafe $text
            $item.dependencies = @($manifest.items | Where-Object {
                $_.id -ne $item.id -and ($text.Contains($_.id, [StringComparison]::OrdinalIgnoreCase) -or
                    ($_.type -eq 'Lakehouse' -and ($text.Contains($_.lakehouse.properties.sqlEndpointProperties.id, [StringComparison]::OrdinalIgnoreCase) -or
                        $text.Contains($_.lakehouse.sqlServer, [StringComparison]::OrdinalIgnoreCase))))
            } | ForEach-Object { $_.id })
            if ($item.type -ne 'Lakehouse') { continue }
            foreach ($area in 'Tables','Files') {
                $uri = Get-EstateOneLakeUri $item.workspaceId $item.id $area
                $item.lakehouse.areas[$area] = @(Get-EstateRemoteFiles $uri $config.tenantId)
            }
            $item.lakehouse.sqlSnapshot = Get-FabricEstateSqlSnapshot -Server $item.lakehouse.sqlServer `
                -Database $item.lakehouse.sqlDatabase -SqlClientDirectory $SqlClientDirectory `
                -RequireZavaContract:$item.lakehouse.requireZavaContract
            if ($item.lakehouse.sqlSnapshot.sqlObjects.Count) {
                throw "Lakehouse $($item.id) has custom SQL objects. Inventory their DDL/dependencies and add a reviewed restore step before a complete export."
            }
            Assert-EstateDeltaTables $item.lakehouse
        }
        [void]@(Get-EstateItemOrder $manifest.items)
        Write-EstateJson $manifestPath $manifest
        foreach ($item in @($manifest.items | Where-Object { $_.type -eq 'Lakehouse' })) {
            foreach ($area in 'Tables','Files') {
                $directory = Resolve-EstatePath $payload "items/$($item.id)/data/$area"
                [void](New-Item -ItemType Directory -Path $directory -Force)
                if ($item.lakehouse.areas[$area].Count) {
                    Copy-EstateData (Get-EstateOneLakeUri $item.workspaceId $item.id $area) $directory $config.tenantId
                }
                Assert-EstateListingMatches $item.lakehouse.areas[$area] @(Get-EstateFiles $directory)
            }
        }
        foreach ($item in $manifest.items) {
            $checkDirectory = Join-Path $OutputPath "readback-$($item.id)"
            Export-EstateDefinition $item.workspaceId $item.id $item.type $checkDirectory
            Assert-EstateFiles $checkDirectory @(Get-EstateFiles (Resolve-EstatePath $payload $item.definitionPath))
            if ($item.type -ne 'Lakehouse') { continue }
            foreach ($area in 'Tables','Files') {
                Assert-EstateListingMatches $item.lakehouse.areas[$area] `
                    @(Get-EstateRemoteFiles (Get-EstateOneLakeUri $item.workspaceId $item.id $area) $config.tenantId) -IncludeModified
            }
            $after = Get-FabricEstateSqlSnapshot -Server $item.lakehouse.sqlServer -Database $item.lakehouse.sqlDatabase `
                -SqlClientDirectory $SqlClientDirectory -RequireZavaContract:$item.lakehouse.requireZavaContract
            $differences = Compare-FabricEstateSqlSnapshot $item.lakehouse.sqlSnapshot $after -CompareSecurity
            Write-EstateJson (Join-Path $OutputPath "readback-$($item.id)-sql.json") @{snapshot=$after;differences=$differences}
            if ($differences.Count) {
                throw "Source SQL snapshot changed during export: $($item.id)"
            }
        }
        foreach ($workspace in $manifest.workspaces) {
            $after = Get-EstateWorkspaceInventory $workspace.id
            if ((ConvertTo-EstateCanonicalJson $workspace) -cne (ConvertTo-EstateCanonicalJson $after)) {
                throw "Workspace inventory, schedules or permissions changed during export: $($workspace.id)"
            }
        }
        $manifest.files = @(Get-EstateFiles $payload)
        $manifest.finishedUtc = [DateTimeOffset]::UtcNow.ToString('o')
        $manifest.status = 'complete'
        Write-EstateJson $manifestPath $manifest
        return [ordered]@{
            status='complete'; manifest=$manifestPath
            manifestSha256=(Get-FileHash -LiteralPath $manifestPath -Algorithm SHA256).Hash.ToLowerInvariant()
            itemCount=$manifest.items.Count; fileCount=$manifest.files.Count
            cutoverApproved=$false
        }
    } catch {
        if ($manifest.status -notin 'blocked','inventoryOnly') { $manifest.status = 'incomplete' }
        Write-EstateJson $manifestPath $manifest
        throw
    }
}

function Import-FabricEstate {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$PackagePath,
        [Parameter(Mandatory)][string]$ManifestSha256,
        [Parameter(Mandatory)][string]$TargetMap,
        [Parameter(Mandatory)][string]$ReceiptPath,
        [switch]$Apply,
        [switch]$TargetIsolated,
        [switch]$AllowPreviewDataAgent
    )
    $manifest = Read-EstatePackage $PackagePath $ManifestSha256
    $mapping = Read-EstateTarget $TargetMap $manifest
    Assert-EstateLocalPath $ReceiptPath -OutsideRepository
    Assert-EstateSeparatePath $ReceiptPath $PackagePath
    $target = $mapping.config
    if (@($manifest.items | Where-Object { $_.type -eq 'DataAgent' }).Count -and !$AllowPreviewDataAgent) {
        throw 'Importing DataAgent definitions requires -AllowPreviewDataAgent.'
    }
    if ($Apply -and !$TargetIsolated) { throw 'Apply requires -TargetIsolated: no users, writers, refreshes or scheduled jobs may access the target yet.' }
    Assert-EstateTenant $target.tenantId
    Assert-EstateFabricAuth $target.tenantId
    $mapHash = (Get-FileHash -LiteralPath $TargetMap -Algorithm SHA256).Hash
    $receipt = [ordered]@{
        version=1; manifestSha256=$ManifestSha256; targetMapSha256=$mapHash
        targetTenantId=$target.tenantId; status='planned'; items=@{}; cutoverApproved=$false
    }
    if (Test-Path -LiteralPath $ReceiptPath) {
        $receipt = Read-EstateJson $ReceiptPath
        if ($receipt.version -ne 1 -or $receipt.manifestSha256 -ne $ManifestSha256 -or $receipt.targetMapSha256 -ne $mapHash) {
            throw 'Receipt belongs to a different package or target map.'
        }
        if ($receipt.status -eq 'inProgress') { throw 'Interrupted import: inspect the remote job/partial target before retrying. Use a new empty target and new receipt; no automatic destructive recovery.' }
    }
    $targetInventory = @{}
    foreach ($workspaceId in $mapping.workspaces.Values) { $targetInventory[$workspaceId] = Get-EstateWorkspaceInventory $workspaceId }
    $bindings = @{}
    foreach ($key in $mapping.workspaces.Keys) { $bindings[$key] = $mapping.workspaces[$key] }
    foreach ($binding in $target.bindings) {
        if ($bindings.ContainsKey($binding.source)) { throw 'Duplicate binding.' }
        $bindings[$binding.source] = $binding.target
    }
    foreach ($item in $manifest.items) {
        $destination = $mapping.items[$item.id]
        $workspaceId = $mapping.workspaces[$item.workspaceId]
        $existing = @($targetInventory[$workspaceId].items | Where-Object { $_.displayName -eq $destination.displayName -and $_.type -eq $item.type })
        if ($item.type -eq 'Lakehouse') {
            if ($existing.Count -ne 1 -or $existing[0].id -ne $destination.targetId) { throw "Precreate the named empty target lakehouse and map its exact ID: $($destination.displayName)" }
            Assert-EstateLakehouseEndpoint $existing[0] $destination
            $sourceSchema = Get-EstateDefaultSchema $item.lakehouse.properties
            $targetSchema = Get-EstateDefaultSchema $existing[0].properties
            if ($sourceSchema -cne $targetSchema) { throw 'Source/target Lakehouse schema mode or default schema differs.' }
            if (@($targetInventory[$workspaceId].shortcuts[$destination.targetId]).Count) { throw 'Target Lakehouse contains shortcuts.' }
            if (@($targetInventory[$workspaceId].schedules[$destination.targetId]).Count) { throw 'Target Lakehouse has schedules; stop/remove them before importing.' }
            if ($destination.requireZavaContract -ne $item.lakehouse.requireZavaContract) { throw 'Target cannot weaken the source Zava validation contract.' }
            $bindings[$item.id] = $destination.targetId
            Add-EstateSqlBindings $bindings $item $existing[0] $destination
            foreach ($area in 'Tables','Files') {
                $remote = @(Get-EstateRemoteFiles (Get-EstateOneLakeUri $workspaceId $destination.targetId $area) $target.tenantId)
                if (!$receipt.items.Contains($item.id) -and $remote.Count) { throw "Target $($destination.displayName)/$area is not empty. Nothing will be overwritten." }
            }
        } elseif ($existing.Count -and !$receipt.items.Contains($item.id)) {
            throw "Target item already exists: $($destination.displayName). Use a distinct target name."
        }
        if ($receipt.items.Contains($item.id)) {
            $record = $receipt.items[$item.id]
            if ($existing.Count -ne 1 -or $existing[0].id -ne $record.targetId) { throw 'Receipt target item no longer matches the workspace.' }
            $bindings[$item.id] = $record.targetId
        }
    }
    $ordered = @(Get-EstateItemOrder $manifest.items)
    # Validate all rewrites before the first write, using temporary IDs for not-yet-created items.
    $preflightBindings = $bindings.Clone()
    foreach ($item in $manifest.items) {
        if (!$preflightBindings.ContainsKey($item.id)) { $preflightBindings[$item.id] = [guid]::NewGuid().ToString() }
    }
    $forbidden = @($manifest.items | ForEach-Object { $_.id }) + @($mapping.workspaces.Keys) + @($target.bindings | ForEach-Object { $_.source })
    foreach ($item in $manifest.items | Where-Object { $_.type -ne 'Lakehouse' }) {
        $definition = Resolve-EstatePath (Join-Path $PackagePath 'payload') $item.definitionPath
        foreach ($part in @(Get-EstateDefinitionParts $definition | Where-Object { $_.path -ne '.platform' })) {
            $text = Convert-EstateDefinitionText $part.text $preflightBindings $forbidden
            if ([IO.Path]::GetExtension($part.path) -in '.json','.ipynb') { [void](ConvertTo-EstateCanonicalText $text) }
        }
    }
    if (!$Apply) {
        return [ordered]@{
            status='planned'; targetTenantId=$target.tenantId; sourceTenantId=$manifest.sourceTenantId
            order=@($ordered | ForEach-Object { @{sourceId=$_.id;type=$_.type;targetName=$mapping.items[$_.id].displayName} })
            message='Read-only preflight passed. No remote items/data changed. Apply requires isolated targets. Permissions/publication/cutover remain separate.'
        }
    }
    if ($receipt.status -eq 'imported') { return $receipt }
    $receiptDirectory = Split-Path -Parent ([IO.Path]::GetFullPath($ReceiptPath))
    [void](New-Item -ItemType Directory -Path $receiptDirectory -Force)
    $receipt.status = 'inProgress'
    Write-EstateJson $ReceiptPath $receipt
    $payload = Join-Path $PackagePath 'payload'
    foreach ($item in $ordered) {
        $destination = $mapping.items[$item.id]
        $workspaceId = $mapping.workspaces[$item.workspaceId]
        if ($item.type -eq 'Lakehouse') {
            foreach ($area in 'Tables','Files') {
                $local = Resolve-EstatePath $payload "items/$($item.id)/data/$area"
                if ($item.lakehouse.areas[$area].Count) {
                    Copy-EstateData $local (Get-EstateOneLakeUri $workspaceId $destination.targetId $area) $target.tenantId
                }
                Assert-EstateListingMatches $item.lakehouse.areas[$area] `
                    @(Get-EstateRemoteFiles (Get-EstateOneLakeUri $workspaceId $destination.targetId $area) $target.tenantId)
            }
            $targetId = $destination.targetId
        } else {
            $definitionDirectory = Join-Path $receiptDirectory ("definition-" + $item.id)
            if (Test-Path -LiteralPath $definitionDirectory) { throw "Staged definition directory already exists: $definitionDirectory" }
            Copy-EstateDefinitionWithBindings (Resolve-EstatePath $payload $item.definitionPath) $definitionDirectory $bindings $forbidden
            $targetId = Import-EstateDefinition $workspaceId $destination.displayName $item.type $definitionDirectory -Description $item.description
            $bindings[$item.id] = $targetId
        }
        $receipt.items[$item.id] = [ordered]@{targetId=$targetId;workspaceId=$workspaceId;type=$item.type;displayName=$destination.displayName}
        Write-EstateJson $ReceiptPath $receipt
    }
    $receipt.status = 'imported'
    $receipt['finishedUtc'] = [DateTimeOffset]::UtcNow.ToString('o')
    $receipt['next'] = 'Run Test-FabricEstate. Rebuild Search, rebind the resolver release, review/publish the Data Agent, apply mapped permissions and test real users before cutover.'
    Write-EstateJson $ReceiptPath $receipt
    return $receipt
}

function Test-FabricEstate {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$PackagePath,
        [Parameter(Mandatory)][string]$ManifestSha256,
        [string]$TargetMap,
        [string]$ReceiptPath,
        [string]$ReadbackPath,
        [string]$SqlClientDirectory,
        [switch]$PackageOnly
    )
    $manifest = Read-EstatePackage $PackagePath $ManifestSha256
    if ($PackageOnly) { return @{status='packageValidated';fileCount=$manifest.files.Count;cutoverApproved=$false} }
    if (!$TargetMap -or !$ReceiptPath -or !$ReadbackPath) { throw 'Target validation requires TargetMap, ReceiptPath and a new ReadbackPath.' }
    Assert-EstateLocalPath $ReadbackPath -OutsideRepository
    Assert-EstateSeparatePath $ReadbackPath $PackagePath
    if (Test-Path -LiteralPath $ReadbackPath) { throw 'Choose a new empty readback directory.' }
    $mapping = Read-EstateTarget $TargetMap $manifest
    $receipt = Read-EstateJson $ReceiptPath
    if ($receipt.status -ne 'imported' -or $receipt.manifestSha256 -ne $ManifestSha256 -or
        $receipt.targetMapSha256 -ne (Get-FileHash -LiteralPath $TargetMap -Algorithm SHA256).Hash) {
        throw 'A completed import receipt matching this exact package/map is required.'
    }
    Assert-EstateTenant $mapping.config.tenantId
    Assert-EstateFabricAuth $mapping.config.tenantId
    $targetInventory = @{}
    foreach ($workspaceId in $mapping.workspaces.Values) { $targetInventory[$workspaceId] = Get-EstateWorkspaceInventory $workspaceId }
    [void](New-Item -ItemType Directory -Path $ReadbackPath)
    $report = [ordered]@{status='incomplete';items=@();cutoverApproved=$false}
    Write-EstateJson (Join-Path $ReadbackPath 'validation.json') $report
    foreach ($item in $manifest.items) {
        if (!$receipt.items.Contains($item.id)) { throw "Receipt is missing $($item.id)." }
        $record = $receipt.items[$item.id]
        $expectedWorkspace = $mapping.workspaces[$item.workspaceId]
        if ($record.workspaceId -ne $expectedWorkspace) { throw 'Receipt workspace does not match target map.' }
        Assert-EstateGuid $record.targetId 'receipt target item'
        $live = @($targetInventory[$expectedWorkspace].items | Where-Object { $_.id -eq $record.targetId })
        if ($live.Count -ne 1 -or $live[0].type -ne $item.type -or $live[0].displayName -cne $mapping.items[$item.id].displayName) {
            throw 'Target item identity/type/name differs from the approved map.'
        }
        if ($item.type -eq 'Lakehouse') {
            $destination = $mapping.items[$item.id]
            if ($record.targetId -ne $destination.targetId) { throw 'Receipt lakehouse does not match target map.' }
            Assert-EstateLakehouseEndpoint $live[0] $destination
            if ((Get-EstateDefaultSchema $item.lakehouse.properties) -cne (Get-EstateDefaultSchema $live[0].properties)) {
                throw 'Target Lakehouse schema mode differs.'
            }
            if (@($targetInventory[$expectedWorkspace].shortcuts[$record.targetId]).Count -or @($targetInventory[$expectedWorkspace].schedules[$record.targetId]).Count) {
                throw 'Target Lakehouse shortcuts/schedules appeared during migration.'
            }
            foreach ($area in 'Tables','Files') {
                $directory = Join-Path $ReadbackPath "$($item.id)\$area"
                [void](New-Item -ItemType Directory -Path $directory -Force)
                $uri = Get-EstateOneLakeUri $expectedWorkspace $record.targetId $area
                $before = @(Get-EstateRemoteFiles $uri $mapping.config.tenantId)
                Assert-EstateListingMatches $item.lakehouse.areas[$area] $before
                if ($before.Count) { Copy-EstateData $uri $directory $mapping.config.tenantId }
                $expected = @(Get-EstateFiles (Resolve-EstatePath (Join-Path $PackagePath 'payload') "items/$($item.id)/data/$area"))
                Assert-EstateFiles $directory $expected
                Assert-EstateListingMatches $before @(Get-EstateRemoteFiles $uri $mapping.config.tenantId) -IncludeModified
            }
            $actual = Get-FabricEstateSqlSnapshot -Server $destination.sqlServer -Database $destination.sqlDatabase `
                -SqlClientDirectory $SqlClientDirectory -RequireZavaContract:$destination.requireZavaContract
            $differences = Compare-FabricEstateSqlSnapshot $item.lakehouse.sqlSnapshot $actual
            Write-EstateJson (Join-Path $ReadbackPath "$($item.id)-sql.json") @{snapshot=$actual;differences=$differences}
            if ($differences.Count) { throw "SQL reconciliation failed for $($item.id). Wait for SQL synchronization or investigate the differences; do not activate." }
        } else {
            $directory = Join-Path $ReadbackPath "$($item.id)-definition"
            Export-EstateDefinition $expectedWorkspace $record.targetId $item.type $directory
            Assert-EstateImportedDefinition $item $manifest $mapping $receipt $PackagePath $directory $targetInventory
        }
        $report.items += ,@{sourceId=$item.id;targetId=$record.targetId;status='validated'}
    }
    $report.status = 'dataAndDefinitionsValidated'
    $report['remainingGates'] = @('Target security/principal mapping and allowed/denied real-user tests',
        'Target Search projection and resolver release activation', 'Data Agent runtime/source review, publication and delegated invocation',
        'Application configuration cutover and finance-owner acceptance')
    Write-EstateJson (Join-Path $ReadbackPath 'validation.json') $report
    return $report
}
